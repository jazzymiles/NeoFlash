#!/usr/bin/env python3
"""Build the Actions editor API index (toolbox tree, code hints and Scripting Reference).

The toolbox and code hints offer only declarations that the declaration audit marks as
`implemented_subset` or `partial` (`classes`, `members`); missing and unreviewed entries never
appear there. Each language also carries `missing`: the documented members of the indexed
classes that the catalogue marks `missing`. Only the Scripting Reference reads it, to show the
support status of every member of a class.

Inputs
  docs/progress/actionscript-catalog.json   statuses (versioned, regenerated by progress.py)
  docs/actionscript-reference/*.json        signatures (local reference snapshot, not versioned)

Output
  crates/neoflash-script/assets/actionscript-api.json   (versioned, embedded with include_str!)

Run after any change to declaration statuses:
  python3 scripts/editor-api-index.py          # rewrite the asset
  python3 scripts/editor-api-index.py --check  # fail if built from another catalogue (no reference needed)

`python3 scripts/progress.py --write-reports` runs this automatically when the reference is present.
"""
import hashlib
import json
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CATALOG = ROOT / "docs/progress/actionscript-catalog.json"
AUDIT = ROOT / "docs/progress/actionscript-audit.json"
REFERENCE_FILES = ["as2.json", "as2-components.json", "as2-components-supplement.json", "as3.json"]
OUTPUT = ROOT / "crates/neoflash-script/assets/actionscript-api.json"
SCHEMA_VERSION = 4
GLOBAL_OWNER = "<global>"  # AS3 package-level functions in the reference
READY = {"implemented_subset": "subset", "partial": "partial"}
# Declarations shown under "Language elements" instead of a class or package.
LANGUAGE_KINDS = {"operator", "statement", "directive", "keyword", "special_type", "compiler_directive"}


def resolve_reference_dir():
    """Find docs/actionscript-reference in this tree or the shared git common-dir root."""
    local = ROOT / "docs/actionscript-reference"
    if all((local / name).exists() for name in REFERENCE_FILES):
        return local
    try:
        proc = subprocess.run(
            ["git", "-C", str(ROOT), "rev-parse", "--path-format=absolute", "--git-common-dir"],
            capture_output=True,
            text=True,
            check=False,
        )
        if proc.returncode == 0 and proc.stdout.strip():
            shared = Path(proc.stdout.strip()).parent / "docs/actionscript-reference"
            if all((shared / name).exists() for name in REFERENCE_FILES):
                return shared
    except OSError:
        pass
    return local


REFERENCE = resolve_reference_dir()


def key(entry):
    return (entry["language"].upper(), entry.get("owner") or "", entry["name"], entry["kind"])


def qualified_class(ref, catalog_entry):
    """Qualified name of the class a class declaration defines."""
    if catalog_entry.get("owner"):
        return catalog_entry["owner"]
    package = ref.get("package")
    if package and package != "Top Level":
        return f"{package}.{ref['name']}"
    return ref["name"]


def parents(ref, own):
    """Superclass chain, nearest first. AS3 lists it; AS2 is derived from inherited member pages."""
    if ref.get("inheritance"):
        return [name for name in ref["inheritance"] if name != own]
    chain = []
    for url in ref.get("inherited_member_sources") or []:
        page = url.rsplit("/", 1)[-1].split("#", 1)[0]
        if page.endswith(".html"):
            name = page[: -len(".html")].replace("/", ".")
            if name != own and name not in chain:
                chain.append(name)
    return chain


def value_type(ref, name):
    """Return/value type from the documented signature ('' when the reference gives none)."""
    signature = ref.get("signature") or ""
    kind = ref["kind"]
    if kind in ("method", "function", "constructor"):
        match = re.search(r"\)\s*:\s*([\w.*<>]+)\s*$", signature)
        return match.group(1) if match else ""
    match = re.search(rf"(?<![\w.]){re.escape(name)}\s*:\s*([\w.*<>]+)", signature)
    return match.group(1) if match else ""


def parameters(ref):
    """Parameter list as documented, without the surrounding parentheses."""
    if ref["kind"] not in ("method", "function", "constructor"):
        return None
    signature = ref.get("signature") or ref.get("index_signature") or ""
    start = signature.find("(")
    end = signature.rfind(")")
    return signature[start + 1 : end].strip() if 0 <= start < end else ""


def constant_value(ref):
    """Documented literal value of a constant, when recorded in the reference."""
    if ref["kind"] != "constant":
        return ""
    signature = ref.get("signature") or ""
    match = re.search(r"=\s*(.+?)\s*;?\s*$", signature)
    if match:
        val = match.group(1).strip()
        return val if len(val) <= 64 else ""
    if ref.get("constant_value") is not None:
        val = str(ref["constant_value"]).strip()
        return val if len(val) <= 64 else ""
    return ""


def operator_label(ref, name):
    """Human phrase of an operator when the reference stores it separately from the symbol."""
    raw = (ref.get("operator_name") or "").strip()
    if not raw:
        return ""
    if raw.startswith(name + " "):
        return raw[len(name) + 1 :].strip()
    return raw


def class_entry(ref, own, status, fallback_kind="class"):
    """Compact class or interface record."""
    entry = {
        "parents": parents(ref, own) if ref else [],
        "status": status,
        "kind": ref["kind"] if ref else fallback_kind,
    }
    if ref:
        implements = [name for name in (ref.get("implements") or []) if name and name != own]
        if implements:
            entry["implements"] = implements
    return entry


def member_entry(entry, ref, status):
    """Compact member record shared by the ready and the missing lists."""
    owner = entry.get("owner") or ""
    member = {
        "owner": "" if owner == GLOBAL_OWNER else owner,
        "name": entry["name"],
        "kind": entry["kind"],
        "type": value_type(ref, entry["name"]),
        "status": status,
    }
    if ref.get("static"):
        member["static"] = True
    if ref.get("read_only") is True or ref.get("read_write") == "read_only":
        member["readOnly"] = True
    params = parameters(ref)
    if params is not None:
        member["params"] = params
    val = constant_value(ref)
    if val:
        member["value"] = val
    op = operator_label(ref, entry["name"])
    if op:
        member["operator"] = op
    return member


def missing_members(catalog, references, languages):
    """Missing catalogue members of the indexed classes, with their documented signature.

    Returns the per-language lists and the number of missing members left out because the
    reference has no signature for them (the Reference then shows nothing for those).
    """
    missing = {name: [] for name in languages}
    unjoined = 0
    for entry in catalog:
        if entry["status"] != "missing" or entry["kind"] in ("class", "interface", "package"):
            continue
        owner = entry.get("owner") or ""
        if not owner or owner == GLOBAL_OWNER or owner not in languages[entry["language"]]["classes"]:
            continue
        ref = references.get(key(entry))
        if ref is None:
            unjoined += 1
            continue
        missing[entry["language"]].append(member_entry(entry, ref, "missing"))
    for members in missing.values():
        members.sort(key=lambda m: (m["owner"], m["name"], m["kind"]))
    return missing, unjoined


def build():
    catalog = json.loads(CATALOG.read_text())["entries"]
    limits = {
        (rule["id"], entry["catalogId"]): entry.get("scopeNote", "")
        for rule in json.loads(AUDIT.read_text())["rules"]
        for entry in rule.get("reviewedEntries", [])
    }
    # A metadata-only refresh can use the versioned signatures if their catalogue hash is
    # unchanged. Never generate new API declarations without the local reference snapshot.
    if any(not (REFERENCE / name).exists() for name in REFERENCE_FILES) and OUTPUT.exists():
        existing = json.loads(OUTPUT.read_text())
        current = existing.get("catalogSha256") == hashlib.sha256(CATALOG.read_bytes()).hexdigest()
        # The missing lists and reference metadata need schema >= 4.
        if (
            current
            and existing.get("schemaVersion", 0) >= SCHEMA_VERSION
            and all("missing" in api for api in existing["languages"].values())
        ):
            entries = {}
            for entry in catalog:
                language, owner, name, kind = key(entry)
                entries.setdefault((language, "" if owner == GLOBAL_OWNER else owner, name, kind), []).append(entry)
            for language, api in existing["languages"].items():
                for member in api["members"]:
                    member.pop("limitation", None)
                    matches = entries.get((language, member["owner"], member["name"], member["kind"]), [])
                    notes = {limits.get((entry["rule_id"], entry["catalog_id"]), "") for entry in matches if entry["status"] == "partial"}
                    if matches and all(entry["status"] == "partial" for entry in matches) and len(notes) == 1 and "" not in notes:
                        member["limitation"] = notes.pop()
            existing["schemaVersion"] = SCHEMA_VERSION
            existing["auditSha256"] = hashlib.sha256(AUDIT.read_bytes()).hexdigest()
            return existing
    references = {}
    class_refs = {}  # qualified class name -> reference entry, whatever its audit status
    for name in REFERENCE_FILES:
        path = REFERENCE / name
        if not path.exists():
            sys.exit(f"missing {path}: restore the local reference snapshot first")
        for ref in json.loads(path.read_text())["entries"]:
            references.setdefault(key(ref), ref)
            if ref["kind"] in ("class", "interface"):
                class_refs.setdefault((ref["language"].upper(), qualified_class(ref, ref)), ref)
    languages = {"AS2": {"classes": {}, "members": []}, "AS3": {"classes": {}, "members": []}}
    unjoined = []
    for entry in catalog:
        status = READY.get(entry["status"])
        if status is None:
            continue
        ref = references.get(key(entry))
        if ref is None:
            unjoined.append(entry["catalog_id"])
            continue
        language = languages[entry["language"]]
        kind = entry["kind"]
        if kind == "class" or kind == "interface":
            name = qualified_class(ref, entry)
            language["classes"][name] = class_entry(ref, name, status, kind)
            continue
        group = "language" if kind in LANGUAGE_KINDS or ref.get("scope") == "language" and not entry.get("owner") else ""
        member = member_entry(entry, ref, status)
        if status == "partial":
            note = limits.get((entry["rule_id"], entry["catalog_id"]))
            if note:
                member["limitation"] = note
        if group:
            member["group"] = group
        language["members"].append(member)
    # Members can be ready while their class declaration is not (for example a partial
    # MovieClip method on a class still marked missing). Keep such owners resolvable with
    # their documented superclass chain so inherited code hints work.
    for language_name, language in languages.items():
        for member in language["members"]:
            owner = member["owner"]
            if owner and "group" not in member and owner not in language["classes"]:
                ref = class_refs.get((language_name, owner))
                language["classes"][owner] = class_entry(ref, owner, "members")
    if unjoined:
        sys.exit(f"{len(unjoined)} ready catalog entries have no reference signature, e.g. {unjoined[:5]}")
    for language in languages.values():
        language["members"].sort(key=lambda m: (m["owner"], m["name"], m["kind"]))
    missing, missing_unjoined = missing_members(catalog, references, languages)
    for name, language in languages.items():
        language["missing"] = missing[name]
    if missing_unjoined:
        print(f"{missing_unjoined} missing members of indexed classes have no reference signature and are left out")
    return {
        "schemaVersion": SCHEMA_VERSION,
        "generatedBy": "scripts/editor-api-index.py",
        "catalogSha256": hashlib.sha256(CATALOG.read_bytes()).hexdigest(),
        "auditSha256": hashlib.sha256(AUDIT.read_bytes()).hexdigest(),
        "statuses": sorted(READY),
        "languages": languages,
    }


def main():
    if "--check" in sys.argv:
        # Cheap staleness check without the local reference: the asset records the catalogue
        # hash it was built from. Any status change rewrites the catalogue and its hash.
        current = hashlib.sha256(CATALOG.read_bytes()).hexdigest()
        built = json.loads(OUTPUT.read_text()) if OUTPUT.exists() else {}
        if built.get("catalogSha256") != current or built.get("auditSha256") != hashlib.sha256(AUDIT.read_bytes()).hexdigest():
            sys.exit(f"{OUTPUT.relative_to(ROOT)} is stale: run python3 scripts/editor-api-index.py")
        return
    text = json.dumps(build(), ensure_ascii=False, separators=(",", ":"), sort_keys=True) + "\n"
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(text)
    data = json.loads(text)["languages"]
    print(
        f"wrote {OUTPUT.relative_to(ROOT)}: "
        + ", ".join(
            f"{lang} {len(v['classes'])} classes / {len(v['members'])} members / {len(v.get('missing', []))} missing"
            for lang, v in data.items()
        )
    )


if __name__ == "__main__":
    main()
