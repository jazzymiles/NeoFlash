#!/usr/bin/env python3
"""Build the Actions editor API index (toolbox tree and code hints).

The editor offers only declarations that the declaration audit marks as
`implemented_subset` or `partial`; missing and unreviewed entries never appear.

Inputs
  docs/progress/actionscript-catalog.json   statuses (versioned, regenerated by progress.py)
  docs/actionscript-reference/*.json        signatures (local reference snapshot, not versioned)

Output
  crates/neoflash-editor/assets/actionscript-api.json   (versioned, embedded with include_str!)

Run after any change to declaration statuses:
  python3 scripts/editor-api-index.py          # rewrite the asset
  python3 scripts/editor-api-index.py --check  # fail if built from another catalogue (no reference needed)

`python3 scripts/progress.py --write-reports` runs this automatically when the reference is present.
"""
import hashlib
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CATALOG = ROOT / "docs/progress/actionscript-catalog.json"
REFERENCE = ROOT / "docs/actionscript-reference"
REFERENCE_FILES = ["as2.json", "as2-components.json", "as2-components-supplement.json", "as3.json"]
OUTPUT = ROOT / "crates/neoflash-editor/assets/actionscript-api.json"
GLOBAL_OWNER = "<global>"  # AS3 package-level functions in the reference
READY = {"implemented_subset": "subset", "partial": "partial"}
# Declarations shown under "Language elements" instead of a class or package.
LANGUAGE_KINDS = {"operator", "statement", "directive", "keyword", "special_type", "compiler_directive"}


def key(entry):
    return (entry["language"].upper(), entry.get("owner") or "", entry["name"], entry["kind"])


def qualified_class(ref, catalog_entry):
    """Qualified name of the class a class declaration defines."""
    if catalog_entry.get("owner"):
        return catalog_entry["owner"]
    package = ref.get("package")
    if package and package != "Top Level":
        return f"{package}.{ref['name']}"
    return ref["name"]


def parents(ref, own):
    """Superclass chain, nearest first. AS3 lists it; AS2 is derived from inherited member pages."""
    if ref.get("inheritance"):
        return [name for name in ref["inheritance"] if name != own]
    chain = []
    for url in ref.get("inherited_member_sources") or []:
        page = url.rsplit("/", 1)[-1].split("#", 1)[0]
        if page.endswith(".html"):
            name = page[: -len(".html")].replace("/", ".")
            if name != own and name not in chain:
                chain.append(name)
    return chain


def value_type(ref, name):
    """Return/value type from the documented signature ('' when the reference gives none)."""
    signature = ref.get("signature") or ""
    kind = ref["kind"]
    if kind in ("method", "function", "constructor"):
        match = re.search(r"\)\s*:\s*([\w.*<>]+)\s*$", signature)
        return match.group(1) if match else ""
    match = re.search(rf"(?<![\w.]){re.escape(name)}\s*:\s*([\w.*<>]+)", signature)
    return match.group(1) if match else ""


def parameters(ref):
    """Parameter list as documented, without the surrounding parentheses."""
    if ref["kind"] not in ("method", "function", "constructor"):
        return None
    signature = ref.get("signature") or ref.get("index_signature") or ""
    start = signature.find("(")
    end = signature.rfind(")")
    return signature[start + 1 : end].strip() if 0 <= start < end else ""


def build():
    catalog = json.loads(CATALOG.read_text())["entries"]
    references = {}
    class_refs = {}  # qualified class name -> reference entry, whatever its audit status
    for name in REFERENCE_FILES:
        path = REFERENCE / name
        if not path.exists():
            sys.exit(f"missing {path.relative_to(ROOT)}: restore the local reference snapshot first")
        for ref in json.loads(path.read_text())["entries"]:
            references.setdefault(key(ref), ref)
            if ref["kind"] in ("class", "interface"):
                class_refs.setdefault((ref["language"].upper(), qualified_class(ref, ref)), ref)
    languages = {"AS2": {"classes": {}, "members": []}, "AS3": {"classes": {}, "members": []}}
    unjoined = []
    for entry in catalog:
        status = READY.get(entry["status"])
        if status is None:
            continue
        ref = references.get(key(entry))
        if ref is None:
            unjoined.append(entry["catalog_id"])
            continue
        language = languages[entry["language"]]
        kind = entry["kind"]
        if kind == "class" or kind == "interface":
            name = qualified_class(ref, entry)
            language["classes"][name] = {"parents": parents(ref, name), "status": status, "kind": kind}
            continue
        group = "language" if kind in LANGUAGE_KINDS or ref.get("scope") == "language" and not entry.get("owner") else ""
        owner = entry.get("owner") or ""
        member = {
            "owner": "" if owner == GLOBAL_OWNER else owner,
            "name": entry["name"],
            "kind": kind,
            "type": value_type(ref, entry["name"]),
            "status": status,
        }
        if ref.get("static"):
            member["static"] = True
        params = parameters(ref)
        if params is not None:
            member["params"] = params
        if group:
            member["group"] = group
        language["members"].append(member)
    # Members can be ready while their class declaration is not (for example a partial
    # MovieClip method on a class still marked missing). Keep such owners resolvable with
    # their documented superclass chain so inherited code hints work.
    for language_name, language in languages.items():
        for member in language["members"]:
            owner = member["owner"]
            if owner and "group" not in member and owner not in language["classes"]:
                ref = class_refs.get((language_name, owner))
                language["classes"][owner] = {
                    "parents": parents(ref, owner) if ref else [],
                    "status": "members",
                    "kind": ref["kind"] if ref else "class",
                }
    if unjoined:
        sys.exit(f"{len(unjoined)} ready catalog entries have no reference signature, e.g. {unjoined[:5]}")
    for language in languages.values():
        language["members"].sort(key=lambda m: (m["owner"], m["name"], m["kind"]))
    return {
        "schemaVersion": 1,
        "generatedBy": "scripts/editor-api-index.py",
        "catalogSha256": hashlib.sha256(CATALOG.read_bytes()).hexdigest(),
        "statuses": sorted(READY),
        "languages": languages,
    }


def main():
    if "--check" in sys.argv:
        # Cheap staleness check without the local reference: the asset records the catalogue
        # hash it was built from. Any status change rewrites the catalogue and its hash.
        current = hashlib.sha256(CATALOG.read_bytes()).hexdigest()
        built = json.loads(OUTPUT.read_text()).get("catalogSha256") if OUTPUT.exists() else None
        if built != current:
            sys.exit(f"{OUTPUT.relative_to(ROOT)} is stale: run python3 scripts/editor-api-index.py")
        return
    text = json.dumps(build(), ensure_ascii=False, separators=(",", ":"), sort_keys=True) + "\n"
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(text)
    data = json.loads(text)["languages"]
    print(
        f"wrote {OUTPUT.relative_to(ROOT)}: "
        + ", ".join(f"{lang} {len(v['classes'])} classes / {len(v['members'])} members" for lang, v in data.items())
    )


if __name__ == "__main__":
    main()
