//! Swift 6 `SwiftHostContract.swift` and `GeneratedScenes.swift` code generator (`T-455`).

use super::{
    XcodeScriptBundle, XcodeSwiftProxyMethod, XcodeSymbolScriptBundle,
    app_shell::format_swift_method_signature, pascal_case_identifier, sanitize_swift_identifier,
};
