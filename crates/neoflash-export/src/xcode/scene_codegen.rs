pub(super) struct GeneratedSceneOutput {
    pub host_contract_swift: String,
    pub scenes_swift: String,
    pub exported_symbol_count: usize,
}

#[must_use]
pub(super) fn render_swift_host_contract(host_methods: &[XcodeSwiftProxyMethod]) -> String {
    let mut out = String::new();
    let _ = writeln!(out, "// DO NOT EDIT — generated by NeoFlash");
    let _ = writeln!(out, "import Foundation");
    let _ = writeln!(out, "import CoreGraphics");
    let _ = writeln!(out);
    let _ = writeln!(out, "@MainActor");
    let _ = writeln!(out, "public protocol SwiftHostProtocol: AnyObject {{");
    for method in host_methods {
        let sig = format_swift_method_signature(method);
        let _ = writeln!(out, "    {sig}");
    }
    let _ = writeln!(out, "}}");
    out
}

pub(super) fn generate_scenes_and_contract(
    project: &Project,
    resource_filenames: &BTreeMap<String, String>,
    font_family_overrides: &BTreeMap<String, String>,
    scripts: Option<&XcodeScriptBundle>,
) -> GeneratedSceneOutput {
    let host_methods = scripts.map(|s| s.host_methods.as_slice()).unwrap_or(&[]);
    let host_contract_swift = render_swift_host_contract(host_methods);

    let (flattened_cow, scene_ranges) = flatten_scenes_cow(project);
    let flattened = flattened_cow.as_ref();

    let mut script_by_symbol: BTreeMap<&str, &XcodeSymbolScriptBundle> = BTreeMap::new();
    if let Some(bundle) = scripts {
        for sym_script in &bundle.symbols {
            script_by_symbol.insert(sym_script.symbol_id.as_str(), sym_script);
        }
    }

    // Collect non-secondary-scene symbols (root first, then library symbols in deterministic order).
    let mut ordered_symbols: Vec<&Symbol> = Vec::new();
    if let Some(root_sym) = flattened.symbol(&flattened.root) {
        ordered_symbols.push(root_sym);
    }
    for sym in &flattened.symbols {
        if sym.id == flattened.root || flattened.is_scene(&sym.id) {
            continue;
        }
        ordered_symbols.push(sym);
    }

    // Assign collision-free Swift class names to every exported symbol.
    let mut used_class_names: BTreeSet<String> = BTreeSet::from([
        "NFValue".into(),
        "NFRuntime".into(),
        "NFScriptError".into(),
        "NFError".into(),
        "NFPoint".into(),
        "NFRectangle".into(),
        "NFMatrix".into(),
        "NFAffineMatrix".into(),
        "NFEvent".into(),
        "NFMouseEvent".into(),
        "NFKeyboardEvent".into(),
        "NFTouchEvent".into(),
        "NFEventDispatcher".into(),
        "NFIEventDispatcher".into(),
        "NFDisplayObject".into(),
        "NFSprite".into(),
        "NFMovieClip".into(),
        "NFButton".into(),
        "NFShape".into(),
        "NFTextField".into(),
        "NFBitmap".into(),
        "NFVideo".into(),
        "NFGraphics".into(),
        "NFStage".into(),
        "NFStageInputState".into(),
        "NFRenderer".into(),
        "NFResourceCache".into(),
        "NFAudioManager".into(),
        "NFSound".into(),
        "NFSoundChannel".into(),
        "NFSoundTransform".into(),
        "NFSoundMixer".into(),
        "NFBitmapData".into(),
        "NFBitmapDataBox".into(),
        "NFByteArray".into(),
        "NFEndian".into(),
        "NFCompressionAlgorithm".into(),
        "NFObjectEncoding".into(),
        "NFSharedObject".into(),
        "NFSharedObjectFlushStatus".into(),
        "NFXMLNode".into(),
        "NFXMLDocument".into(),
        "NFXML".into(),
        "NFXMLList".into(),
        "NFNamespace".into(),
        "NFQName".into(),
        "NFPixelSnapping".into(),
        "NFGradientType".into(),
        "NFSpreadMethod".into(),
        "NFInterpolationMethod".into(),
        "NFGraphicsPathWinding".into(),
        "NFGraphicsPathCommand".into(),
        "NFTextFormatAlign".into(),
        "NFBitmapFilterType".into(),
        "NFPNGEncoderOptions".into(),
        "NFJPEGEncoderOptions".into(),
        "NFErrorEvent".into(),
        "NFAsyncErrorEvent".into(),
        "NFTextFormat".into(),
        "NFStyleSheet".into(),
        "NFTextLineMetrics".into(),
        "NFTextFieldAutoSize".into(),
        "NFAntiAliasType".into(),
        "NFGridFitType".into(),
        "NFTransform".into(),
        "NFAS2Color".into(),
        "NFVector3D".into(),
        "NFMatrix3D".into(),
        "NFPerspectiveProjection".into(),
        "NFTimer".into(),
        "NFTimerEvent".into(),
        "NFDate".into(),
        "NFJSON".into(),
        "NFRegExp".into(),
        "NFNumberFormatter".into(),
        "NFLocale".into(),
        "NFIOErrorEvent".into(),
        "NFSecurityErrorEvent".into(),
        "NFProgressEvent".into(),
        "NFHTTPStatusEvent".into(),
        "NFTextEvent".into(),
        "NFFocusEvent".into(),
        "NFNetStatusEvent".into(),
        "NFURLRequest".into(),
        "NFURLVariables".into(),
        "NFURLLoader".into(),
        "NFURLLoaderDataFormat".into(),
        "NFLoadVars".into(),
        "NFLoader".into(),
        "NFLoaderInfo".into(),
        "NFMovieClipLoader".into(),
        "NFNetConnection".into(),
        "NFNetStream".into(),
        "NFSystem".into(),
        "NFCapabilities".into(),
        "NFMouse".into(),
        "NFSelection".into(),
        "NFFrameLabel".into(),
        "NFDepthManager".into(),
        "NFCamera".into(),
        "NFMicrophone".into(),
        "NFLocalConnection".into(),
        "NFFileReference".into(),
        "NFFileFilter".into(),
        "NFContextMenu".into(),
        "NFContextMenuItem".into(),
        "NFPrintJob".into(),
        "NeoFlashStageView".into(),
        "SwiftHostProtocol".into(),
        "AppSwiftHost".into(),
        "ContentView".into(),
        "NFGeneratedSymbolRegistry".into(),
    ]);
    let linked_source_class_names: BTreeSet<String> = scripts
        .map(|b| {
            b.symbols
                .iter()
                .filter(|s| s.is_linked_source_class && !s.swift_class_name.trim().is_empty())
                .map(|s| s.swift_class_name.trim().to_owned())
                .collect()
        })
        .unwrap_or_default();
    if let Some(bundle) = scripts {
        for line in bundle.source_classes_swift.lines() {
            let trimmed = line.trim_start();
            for prefix in [
                "open class ",
                "public class ",
                "public final class ",
                "public protocol ",
            ] {
                if let Some(rest) = trimmed.strip_prefix(prefix) {
                    let ident: String = rest
                        .chars()
                        .take_while(|c| c.is_ascii_alphanumeric() || *c == '_')
                        .collect();
                    if !ident.is_empty() && !linked_source_class_names.contains(&ident) {
                        used_class_names.insert(ident);
                    }
                }
            }
        }
    }

    let mut class_name_by_symbol_id: BTreeMap<String, String> = BTreeMap::new();
    let mut needs_main_scene_typealias: Option<String> = None;

    for sym in &ordered_symbols {
        let is_root = sym.id == flattened.root;
        let sym_bundle = script_by_symbol.get(sym.id.as_str()).copied();
        if let Some(bundle) = sym_bundle
            && bundle.is_linked_source_class
            && !bundle.swift_class_name.trim().is_empty()
        {
            let exact = bundle.swift_class_name.trim().to_owned();
            used_class_names.insert(exact.clone());
            if is_root && exact != "MainScene" {
                needs_main_scene_typealias = Some(exact.clone());
            }
            class_name_by_symbol_id.insert(sym.id.clone(), exact);
            continue;
        }

        let requested = sym_bundle
            .map(|b| b.swift_class_name.trim())
            .filter(|s| !s.is_empty());

        let base_name = if is_root {
            if let Some(req) = requested {
                let clean = pascal_case_identifier(req, "MainScene");
                if clean != "MainScene" {
                    needs_main_scene_typealias = Some(clean.clone());
                }
                clean
            } else {
                "MainScene".to_owned()
            }
        } else if let Some(req) = requested {
            pascal_case_identifier(req, "SymClip")
        } else {
            let stem = pascal_case_identifier(&sym.name, "Clip");
            if stem.starts_with("Sym") {
                stem
            } else {
                format!("Sym{stem}")
            }
        };

        let mut candidate = base_name.clone();
        let mut suffix = 2usize;
        while !used_class_names.insert(candidate.clone()) {
            candidate = format!("{base_name}{suffix}");
            suffix += 1;
        }
        class_name_by_symbol_id.insert(sym.id.clone(), candidate);
    }

    let mut out = String::with_capacity(16384);
    let _ = writeln!(out, "// DO NOT EDIT — generated by NeoFlash");
    let _ = writeln!(out, "import Foundation");
    let _ = writeln!(out, "import CoreGraphics");
    let _ = writeln!(out);

    if let Some(bundle) = scripts
        && !bundle.source_classes_swift.trim().is_empty()
    {
        let _ = writeln!(out, "// MARK: - Converted Project Source Classes");
        out.push_str(bundle.source_classes_swift.trim());
        let _ = writeln!(out, "\n");
    }

    let (sound_links, bitmap_links, path_links) =
        collect_resource_linkage_maps(flattened, resource_filenames);

    // Emit centralized symbol & resource factory registry
    let _ = writeln!(out, "@MainActor");
    let _ = writeln!(out, "public enum NFGeneratedSymbolRegistry {{");
    let _ = writeln!(out, "    private static var _didRegisterResources = false");
    let _ = writeln!(out);
    let _ = writeln!(out, "    public static func registerResourcesIfNeeded() {{");
    let _ = writeln!(
        out,
        "        guard !_didRegisterResources else {{ return }}"
    );
    let _ = writeln!(out, "        _didRegisterResources = true");
    for (k, v) in &sound_links {
        let _ = writeln!(
            out,
            "        if NFAudioManager.shared.soundLinkageMap[{}] == nil {{ NFAudioManager.shared.soundLinkageMap[{}] = {} }}",
            swift_str(k),
            swift_str(k),
            swift_str(v)
        );
    }
    for (k, v) in &bitmap_links {
        let _ = writeln!(
            out,
            "        if NFResourceCache.shared.bitmapLinkageMap[{}] == nil {{ NFResourceCache.shared.bitmapLinkageMap[{}] = {} }}",
            swift_str(k),
            swift_str(k),
            swift_str(v)
        );
    }
    for (k, v) in &path_links {
        let _ = writeln!(
            out,
            "        if NFResourceCache.shared.resourcePathMap[{}] == nil {{ NFResourceCache.shared.resourcePathMap[{}] = {} }}",
            swift_str(k),
            swift_str(k),
            swift_str(v)
        );
    }
    let _ = writeln!(out, "    }}");
    let _ = writeln!(out);
    let _ = writeln!(
        out,
        "    public static func instantiate(_ symbolId: String) -> NFDisplayObject? {{"
    );
    let _ = writeln!(out, "        registerResourcesIfNeeded()");
    let _ = writeln!(out, "        switch symbolId {{");
    let mut emitted_case_keys: BTreeSet<String> = BTreeSet::new();
    for sym in &ordered_symbols {
        if sym.id == flattened.root {
            continue;
        }
        if let Some(cls) = class_name_by_symbol_id.get(&sym.id) {
            let mut keys = Vec::new();
            for cand in [
                Some(sym.id.as_str()),
                sym.linkage_id.as_deref(),
                sym.class_name.as_deref(),
                sym.class_name
                    .as_deref()
                    .and_then(|cn| cn.rsplit('.').next()),
            ]
            .into_iter()
            .flatten()
            {
                let trimmed = cand.trim();
                if !trimmed.is_empty() && emitted_case_keys.insert(trimmed.to_owned()) {
                    keys.push(swift_str(trimmed));
                }
            }
            if !keys.is_empty() {
                let _ = writeln!(out, "        case {}: return {cls}()", keys.join(", "));
            }
        }
    }
    let _ = writeln!(out, "        default: return nil");
    let _ = writeln!(out, "        }}");
    let _ = writeln!(out, "    }}");
    let _ = writeln!(out, "}}");
    let _ = writeln!(out);

    if let Some(actual_root_cls) = &needs_main_scene_typealias {
        let _ = writeln!(out, "public typealias MainScene = {actual_root_cls}");
        let _ = writeln!(out);
    }

    for sym in &ordered_symbols {
        let is_root = sym.id == flattened.root;
        let cls_name = &class_name_by_symbol_id[&sym.id];
        let sym_script = script_by_symbol.get(sym.id.as_str()).copied();
        emit_symbol_class(
            &mut out,
            flattened,
            sym,
            cls_name,
            is_root,
            if is_root { &scene_ranges } else { &[] },
            &class_name_by_symbol_id,
            resource_filenames,
            font_family_overrides,
            sym_script,
        );
        let _ = writeln!(out);
    }

    GeneratedSceneOutput {
        host_contract_swift,
        scenes_swift: out,
        exported_symbol_count: ordered_symbols.len(),
    }
}

