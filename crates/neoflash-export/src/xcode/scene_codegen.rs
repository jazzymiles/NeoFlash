use std::fmt::Write as _;

pub(super) struct GeneratedSceneOutput {
    pub host_contract_swift: String,
    pub scenes_swift: String,
    pub exported_symbol_count: usize,
}

#[must_use]
pub(super) fn render_swift_host_contract(host_methods: &[XcodeSwiftProxyMethod]) -> String {
    let mut out = String::new();
    let _ = writeln!(out, "// DO NOT EDIT — generated by NeoFlash");
    let _ = writeln!(out, "import Foundation");
    let _ = writeln!(out, "import CoreGraphics");
    let _ = writeln!(out);
    let _ = writeln!(out, "@MainActor");
    let _ = writeln!(out, "public protocol SwiftHostProtocol: AnyObject {{");
    for method in host_methods {
        let sig = format_swift_method_signature(method);
        let _ = writeln!(out, "    {sig}");
    }
    let _ = writeln!(out, "}}");
    out
}

pub(super) fn generate_scenes_and_contract(
    project: &Project,
    resource_filenames: &BTreeMap<String, String>,
    font_family_overrides: &BTreeMap<String, String>,
    scripts: Option<&XcodeScriptBundle>,
) -> GeneratedSceneOutput {
    let host_methods = scripts.map(|s| s.host_methods.as_slice()).unwrap_or(&[]);
    let host_contract_swift = render_swift_host_contract(host_methods);

    let (flattened_cow, scene_ranges) = flatten_scenes_cow(project);
    let flattened = flattened_cow.as_ref();

    let mut script_by_symbol: BTreeMap<&str, &XcodeSymbolScriptBundle> = BTreeMap::new();
    if let Some(bundle) = scripts {
        for sym_script in &bundle.symbols {
            script_by_symbol.insert(sym_script.symbol_id.as_str(), sym_script);
        }
    }

    // Collect non-secondary-scene symbols (root first, then library symbols in deterministic order).
    let mut ordered_symbols: Vec<&Symbol> = Vec::new();
    if let Some(root_sym) = flattened.symbol(&flattened.root) {
        ordered_symbols.push(root_sym);
    }
    for sym in &flattened.symbols {
        if sym.id == flattened.root || flattened.is_scene(&sym.id) {
            continue;
        }
        ordered_symbols.push(sym);
    }

    // Assign collision-free Swift class names to every exported symbol.
    let mut used_class_names: BTreeSet<String> = BTreeSet::from([
        "NFValue".into(),
        "NFDisplayObject".into(),
        "NFSprite".into(),
        "NFMovieClip".into(),
        "NFButton".into(),
        "NFShape".into(),
        "NFTextField".into(),
        "NFBitmap".into(),
        "NFVideo".into(),
        "NFGraphics".into(),
        "NFStage".into(),
        "NFRenderer".into(),
        "NFAudioManager".into(),
        "NeoFlashStageView".into(),
        "SwiftHostProtocol".into(),
        "AppSwiftHost".into(),
        "ContentView".into(),
        "NFGeneratedSymbolRegistry".into(),
    ]);

    let mut class_name_by_symbol_id: BTreeMap<String, String> = BTreeMap::new();
    let mut needs_main_scene_typealias: Option<String> = None;

    for sym in &ordered_symbols {
        let is_root = sym.id == flattened.root;
        let requested = script_by_symbol
            .get(sym.id.as_str())
            .map(|b| b.swift_class_name.trim())
            .filter(|s| !s.is_empty());

        let base_name = if is_root {
            if let Some(req) = requested {
                let clean = pascal_case_identifier(req, "MainScene");
                if clean != "MainScene" {
                    needs_main_scene_typealias = Some(clean.clone());
                }
                clean
            } else {
                "MainScene".to_owned()
            }
        } else if let Some(req) = requested {
            pascal_case_identifier(req, "SymClip")
        } else {
            let stem = pascal_case_identifier(&sym.name, "Clip");
            if stem.starts_with("Sym") {
                stem
            } else {
                format!("Sym{stem}")
            }
        };

        let mut candidate = base_name.clone();
        let mut suffix = 2usize;
        while !used_class_names.insert(candidate.clone()) {
            candidate = format!("{base_name}{suffix}");
            suffix += 1;
        }
        class_name_by_symbol_id.insert(sym.id.clone(), candidate);
    }

    let mut out = String::with_capacity(16384);
    let _ = writeln!(out, "// DO NOT EDIT — generated by NeoFlash");
    let _ = writeln!(out, "import Foundation");
    let _ = writeln!(out, "import CoreGraphics");
    let _ = writeln!(out);

    if let Some(bundle) = scripts
        && !bundle.source_classes_swift.trim().is_empty()
    {
        let _ = writeln!(out, "// MARK: - Converted Project Source Classes");
        out.push_str(bundle.source_classes_swift.trim());
        let _ = writeln!(out, "\n");
    }

    // Emit centralized symbol factory registry
    let _ = writeln!(out, "@MainActor");
    let _ = writeln!(out, "public enum NFGeneratedSymbolRegistry {{");
    let _ = writeln!(
        out,
        "    public static func instantiate(_ symbolId: String) -> NFDisplayObject? {{"
    );
    let _ = writeln!(out, "        switch symbolId {{");
    for sym in &ordered_symbols {
        if sym.id == flattened.root {
            continue;
        }
        if let Some(cls) = class_name_by_symbol_id.get(&sym.id) {
            let mut keys = vec![swift_str(&sym.id)];
            if let Some(link) = &sym.linkage_id
                && !link.trim().is_empty()
                && link != &sym.id
            {
                keys.push(swift_str(link));
            }
            let _ = writeln!(out, "        case {}: return {cls}()", keys.join(", "));
        }
    }
    let _ = writeln!(out, "        default: return nil");
    let _ = writeln!(out, "        }}");
    let _ = writeln!(out, "    }}");
    let _ = writeln!(out, "}}");
    let _ = writeln!(out);

    if let Some(actual_root_cls) = &needs_main_scene_typealias {
        let _ = writeln!(out, "public typealias MainScene = {actual_root_cls}");
        let _ = writeln!(out);
    }

    for sym in &ordered_symbols {
        let is_root = sym.id == flattened.root;
        let cls_name = &class_name_by_symbol_id[&sym.id];
        let sym_script = script_by_symbol.get(sym.id.as_str()).copied();
        emit_symbol_class(
            &mut out,
            flattened,
            sym,
            cls_name,
            is_root,
            if is_root { &scene_ranges } else { &[] },
            &class_name_by_symbol_id,
            resource_filenames,
            font_family_overrides,
            sym_script,
        );
        let _ = writeln!(out);
    }

    GeneratedSceneOutput {
        host_contract_swift,
        scenes_swift: out,
        exported_symbol_count: ordered_symbols.len(),
    }
}

#[derive(Clone, PartialEq)]
struct EncodedShape {
    commands: Vec<PathCommand>,
    fill_rule: FillRule,
    fill: Color,
    fill_gradient: Option<GradientPaint>,
    bitmap_fill: Option<(String, [f64; 6], bool, bool)>,
    stroke: Color,
    stroke_gradient: Option<GradientPaint>,
    stroke_width: f64,
    expanded_stroke: Vec<PathCommand>,
}

#[derive(Clone, PartialEq)]
struct EncodedText {
    text: String,
    font_family: String,
    font_size: f64,
    color: Color,
    bold: bool,
    italic: bool,
    underline: bool,
    align: TextAlign,
    leading: f64,
    letter_spacing: f64,
    box_size: Option<(f64, f64)>,
    word_wrap: bool,
    multiline: bool,
    border: bool,
    border_color: Color,
    background: bool,
    background_color: Color,
}

#[derive(Clone, PartialEq)]
struct EncodedBitmap {
    resource_name: String,
    width: f64,
    height: f64,
    smoothing: bool,
}

#[derive(Clone, PartialEq)]
struct EncodedVideo {
    source: String,
    width: f64,
    height: f64,
}

#[derive(Clone, PartialEq)]
enum EncodedPayload {
    Shape(usize),
    Text(usize),
    Bitmap(usize),
    Video(usize),
    Instance {
        symbol_id: String,
        symbol_kind: SymbolKind,
        playback: InstancePlayback,
        placement_start_frame: u32,
        synced_to_parent: bool,
    },
}

#[derive(Clone, PartialEq)]
struct EncodedPlacement {
    element_id: String,
    name: String,
    x: f64,
    y: f64,
    scale_x: f64,
    scale_y: f64,
    rotation: f64,
    skew: f64,
    matrix: [f64; 6],
    alpha: f64,
    color_transform: ColorTransform,
    visible: bool,
    blend_mode: BlendMode,
    filters: Vec<FilterSpec>,
    payload: EncodedPayload,
}

struct EncodedSpan {
    start_frame: u32,
    end_frame: u32,
    placements: Vec<EncodedPlacement>,
}

struct EncodedLayer {
    layer_index: usize,
    name: String,
    is_mask: bool,
    masked_by_layer_index: Option<usize>,
    blend_mode: BlendMode,
    spans: Vec<EncodedSpan>,
}

#[derive(Clone, PartialEq, Eq)]
struct NamedInstanceBinding {
    raw_name: String,
    swift_prop_name: String,
    swift_type: String,
    init_expr: String,
}

#[allow(clippy::too_many_arguments)]
fn emit_symbol_class(
    out: &mut String,
    project: &Project,
    symbol: &Symbol,
    class_name: &str,
    is_root: bool,
    scene_ranges: &[SceneRange],
    class_name_by_symbol_id: &BTreeMap<String, String>,
    resource_filenames: &BTreeMap<String, String>,
    font_family_overrides: &BTreeMap<String, String>,
    script_bundle: Option<&XcodeSymbolScriptBundle>,
) {
    let fps = f64::from(project.fps.max(1));
    let total_frames = symbol.timeline.frame_count.max(1);
    let stage_center = [project.width as f64 * 0.5, project.height as f64 * 0.5];

    let mut shape_catalog: Vec<EncodedShape> = Vec::new();
    let mut text_catalog: Vec<EncodedText> = Vec::new();
    let mut bitmap_catalog: Vec<EncodedBitmap> = Vec::new();
    let mut video_catalog: Vec<EncodedVideo> = Vec::new();

    let intern_shape = |catalog: &mut Vec<EncodedShape>, candidate: EncodedShape| -> usize {
        if let Some(pos) = catalog.iter().position(|existing| *existing == candidate) {
            pos
        } else {
            catalog.push(candidate);
            catalog.len() - 1
        }
    };

    let intern_text = |catalog: &mut Vec<EncodedText>, candidate: EncodedText| -> usize {
        if let Some(pos) = catalog.iter().position(|existing| *existing == candidate) {
            pos
        } else {
            catalog.push(candidate);
            catalog.len() - 1
        }
    };

    let intern_bitmap = |catalog: &mut Vec<EncodedBitmap>, candidate: EncodedBitmap| -> usize {
        if let Some(pos) = catalog.iter().position(|existing| *existing == candidate) {
            pos
        } else {
            catalog.push(candidate);
            catalog.len() - 1
        }
    };

    let intern_video = |catalog: &mut Vec<EncodedVideo>, candidate: EncodedVideo| -> usize {
        if let Some(pos) = catalog.iter().position(|existing| *existing == candidate) {
            pos
        } else {
            catalog.push(candidate);
            catalog.len() - 1
        }
    };

    let timeline_has_camera = symbol
        .timeline
        .layers
        .iter()
        .flat_map(|l| &l.keyframes)
        .any(|k| k.camera.is_some());

    // Map layer IDs to emitted layer indices (for mask -> masked layer links).
    let mut emitted_layer_indices: BTreeMap<String, usize> = BTreeMap::new();
    let mut visible_layers: Vec<(usize, &Layer)> = Vec::new();
    for layer in &symbol.timeline.layers {
        if !layer_effectively_visible(&symbol.timeline, layer)
            || matches!(layer.properties.role, LayerRole::Folder | LayerRole::Guide)
        {
            continue;
        }
        let idx = visible_layers.len();
        emitted_layer_indices.insert(layer.id.clone(), idx);
        visible_layers.push((idx, layer));
    }

    let mut encoded_layers: Vec<EncodedLayer> = Vec::with_capacity(visible_layers.len());
    for &(layer_idx, layer) in &visible_layers {
        let is_mask = layer.properties.role == LayerRole::Mask;
        let masked_by = if is_mask {
            None
        } else {
            layer
                .properties
                .mask
                .as_ref()
                .and_then(|mid| emitted_layer_indices.get(mid).copied())
        };
        let layer_blend = layer_effective_blend_mode(&symbol.timeline, layer);
        let synced_layer = layer_effectively_synced(&symbol.timeline, layer);

        let layer_end = layer
            .properties
            .end_frame
            .map_or(total_frames, |ef| ef.min(total_frames));

        let mut sorted_keys: Vec<_> = layer
            .keyframes
            .iter()
            .filter(|k| k.frame < layer_end)
            .collect();
        sorted_keys.sort_by_key(|k| k.frame);

        let mut spans: Vec<EncodedSpan> = Vec::new();

        for (k_pos, key) in sorted_keys.iter().enumerate() {
            let span_start = key.frame;
            let span_end = sorted_keys
                .get(k_pos + 1)
                .map_or(layer_end, |nk| nk.frame.min(layer_end));
            if span_start >= span_end {
                continue;
            }

            let needs_per_frame_sampling = key.tween.is_some()
                || motion_span(layer, span_start).is_some()
                || !key.property_expressions.is_empty()
                || (timeline_has_camera && !layer.properties.attach_to_camera);

            if needs_per_frame_sampling && span_end > span_start + 1 {
                for f in span_start..span_end {
                    let placements = encode_frame_elements(
                        project,
                        &symbol.timeline,
                        layer,
                        f,
                        fps,
                        synced_layer,
                        timeline_has_camera,
                        stage_center,
                        resource_filenames,
                        font_family_overrides,
                        &mut shape_catalog,
                        &mut text_catalog,
                        &mut bitmap_catalog,
                        &mut video_catalog,
                        &intern_shape,
                        &intern_text,
                        &intern_bitmap,
                        &intern_video,
                    );
                    if let Some(prev) = spans.last_mut()
                        && prev.end_frame == f
                        && prev.placements == placements
                    {
                        prev.end_frame = f + 1;
                    } else if !placements.is_empty() {
                        spans.push(EncodedSpan {
                            start_frame: f,
                            end_frame: f + 1,
                            placements,
                        });
                    }
                }
            } else {
                let placements = encode_frame_elements(
                    project,
                    &symbol.timeline,
                    layer,
                    span_start,
                    fps,
                    synced_layer,
                    timeline_has_camera,
                    stage_center,
                    resource_filenames,
                    font_family_overrides,
                    &mut shape_catalog,
                    &mut text_catalog,
                    &mut bitmap_catalog,
                    &mut video_catalog,
                    &intern_shape,
                    &intern_text,
                    &intern_bitmap,
                    &intern_video,
                );
                if !placements.is_empty() {
                    spans.push(EncodedSpan {
                        start_frame: span_start,
                        end_frame: span_end,
                        placements,
                    });
                }
            }
        }

        encoded_layers.push(EncodedLayer {
            layer_index: layer_idx,
            name: layer.name.clone(),
            is_mask,
            masked_by_layer_index: masked_by,
            blend_mode: layer_blend,
            spans,
        });
    }

    // Frame sounds
    let mut sounds_by_frame: BTreeMap<u32, Vec<&FrameSound>> = BTreeMap::new();
    for layer in &symbol.timeline.layers {
        if matches!(layer.properties.role, LayerRole::Folder | LayerRole::Guide) {
            continue;
        }
        for key in &layer.keyframes {
            if let Some(snd) = &key.sound {
                sounds_by_frame.entry(key.frame).or_default().push(snd);
            }
        }
    }

    // Collect named stage instances for typed Swift properties
    let named_bindings = collect_named_instance_bindings(
        &encoded_layers,
        class_name_by_symbol_id,
        script_bundle
            .map(|b| b.properties_swift.as_str())
            .unwrap_or(""),
    );

    let superclass = if !is_root && symbol.kind == SymbolKind::Button {
        "NFButton"
    } else {
        "NFMovieClip"
    };
    let conforms_resize =
        script_bundle.is_some_and(|b| b.helper_methods_swift.contains("func onResize()"));
    let conformances = if conforms_resize {
        format!("{superclass}, NFStageResizeListener")
    } else {
        superclass.to_owned()
    };

    let _ = writeln!(out, "@MainActor");
    let _ = writeln!(out, "public final class {class_name}: {conformances} {{");

    // Typed stage instance properties
    for binding in &named_bindings {
        let _ = writeln!(
            out,
            "    public var {}: {} = {}",
            binding.swift_prop_name, binding.swift_type, binding.init_expr
        );
    }
    if !named_bindings.is_empty() {
        let _ = writeln!(out);
    }

    // Custom script properties from XcodeSymbolScriptBundle
    if let Some(bundle) = script_bundle
        && !bundle.properties_swift.trim().is_empty()
    {
        for line in bundle.properties_swift.lines() {
            let _ = writeln!(out, "    {}", line);
        }
        let _ = writeln!(out);
    }

    // Static timeline spec builder so init() stays fast and clean
    emit_timeline_spec_constant(
        out,
        total_frames,
        &symbol.timeline,
        scene_ranges,
        &sounds_by_frame,
        resource_filenames,
        &shape_catalog,
        &text_catalog,
        &bitmap_catalog,
        &video_catalog,
        &encoded_layers,
    );

    let _ = writeln!(
        out,
        "    public override init(name: String = {}) {{",
        swift_str(&symbol.name)
    );
    let _ = writeln!(out, "        super.init(name: name)");
    let sym_kind_swift = if is_root {
        ".movieClip"
    } else {
        match symbol.kind {
            SymbolKind::MovieClip => ".movieClip",
            SymbolKind::Graphic => ".graphic",
            SymbolKind::Button => ".button",
        }
    };
    let _ = writeln!(out, "        self.symbolKind = {sym_kind_swift}");
    if is_root {
        let [r, g, b, a] = project.background;
        let _ = writeln!(
            out,
            "        self.stageMetadata = NFStageMetadata(width: {}, height: {}, fps: {}, backgroundColor: NFColor(r: {r}, g: {g}, b: {b}, a: {a}))",
            fmt_f64(f64::from(project.width)),
            fmt_f64(f64::from(project.height)),
            fmt_f64(fps)
        );
    }
    let _ = writeln!(out, "        self.configureTimeline(Self._nfTimelineSpec)");
    let _ = writeln!(out, "    }}");

    let _ = writeln!(out);
    let _ = writeln!(
        out,
        "    public override func instantiateSymbol(_ symbolId: String) -> NFDisplayObject? {{"
    );
    let _ = writeln!(
        out,
        "        NFGeneratedSymbolRegistry.instantiate(symbolId)"
    );
    let _ = writeln!(out, "    }}");

    if !named_bindings.is_empty() {
        let _ = writeln!(out);
        let _ = writeln!(
            out,
            "    public override func bindPreallocatedNamedChild(_ name: String) -> NFDisplayObject? {{"
        );
        let _ = writeln!(out, "        switch name {{");
        for binding in &named_bindings {
            let _ = writeln!(
                out,
                "        case {}: return self.{}",
                swift_str(&binding.raw_name),
                binding.swift_prop_name
            );
        }
        let _ = writeln!(out, "        default: return nil");
        let _ = writeln!(out, "        }}");
        let _ = writeln!(out, "    }}");
    }

    // Emit script methods & handlers if present
    if let Some(bundle) = script_bundle {
        emit_symbol_script_methods(out, bundle);
    }

    let _ = writeln!(out, "}}");
}

#[allow(clippy::too_many_arguments)]
fn encode_frame_elements<FS, FT, FB, FV>(
    project: &Project,
    timeline: &Timeline,
    layer: &Layer,
    frame: u32,
    fps: f64,
    synced_layer: bool,
    timeline_has_camera: bool,
    stage_center: [f64; 2],
    resource_filenames: &BTreeMap<String, String>,
    font_family_overrides: &BTreeMap<String, String>,
    shape_catalog: &mut Vec<EncodedShape>,
    text_catalog: &mut Vec<EncodedText>,
    bitmap_catalog: &mut Vec<EncodedBitmap>,
    video_catalog: &mut Vec<EncodedVideo>,
    intern_shape: &FS,
    intern_text: &FT,
    intern_bitmap: &FB,
    intern_video: &FV,
) -> Vec<EncodedPlacement>
where
    FS: Fn(&mut Vec<EncodedShape>, EncodedShape) -> usize,
    FT: Fn(&mut Vec<EncodedText>, EncodedText) -> usize,
    FB: Fn(&mut Vec<EncodedBitmap>, EncodedBitmap) -> usize,
    FV: Fn(&mut Vec<EncodedVideo>, EncodedVideo) -> usize,
{
    let active_key = layer.key_at(frame);
    let controllers = active_key
        .map(|k| k.controller_elements.as_slice())
        .unwrap_or(&[]);

    let cam_pose = if timeline_has_camera && !layer.properties.attach_to_camera {
        sample_timeline_camera(timeline, frame)
    } else {
        None
    };
    let layer_cam_matrix = cam_pose
        .as_ref()
        .map(|cam| camera_layer_matrix(cam, layer.properties.z_depth, stage_center));

    let sampled = sample_layer_in_at_fps(timeline, layer, frame, fps);
    let mut out = Vec::with_capacity(sampled.len());

    for el in sampled {
        if controllers.iter().any(|cid| cid == &el.id) {
            continue;
        }
        let local_m = transform_matrix(el.transform);
        let matrix = match layer_cam_matrix {
            Some(cm) => affine_multiply(cm, local_m),
            None => local_m,
        };
        let ct = match &cam_pose {
            Some(cam) => el.transform.color_transform.then(cam.color_transform),
            None => el.transform.color_transform,
        };
        let bitmap_fill_opt = active_key
            .and_then(|k| k.bitmap_fill(&el.id))
            .and_then(|bf| {
                let res_file = resource_filenames.get(&bf.resource_id)?.clone();
                Some((res_file, bf.matrix, bf.repeat, bf.smoothing))
            });

        let payload = match encode_element_payload(
            project,
            layer,
            frame,
            synced_layer,
            &el,
            active_key,
            bitmap_fill_opt,
            resource_filenames,
            font_family_overrides,
            shape_catalog,
            text_catalog,
            bitmap_catalog,
            video_catalog,
            intern_shape,
            intern_text,
            intern_bitmap,
            intern_video,
        ) {
            Some(p) => p,
            None => continue,
        };

        out.push(EncodedPlacement {
            element_id: el.id,
            name: el.name,
            x: el.transform.x,
            y: el.transform.y,
            scale_x: el.transform.scale_x,
            scale_y: el.transform.scale_y,
            rotation: el.transform.rotation,
            skew: el.transform.skew,
            matrix,
            alpha: el.transform.alpha.clamp(0.0, 1.0),
            color_transform: ct,
            visible: el.visible,
            blend_mode: el.blend_mode,
            filters: el.filters,
            payload,
        });
    }

    out
}

#[allow(clippy::too_many_arguments)]
fn encode_element_payload<FS, FT, FB, FV>(
    project: &Project,
    layer: &Layer,
    frame: u32,
    synced_layer: bool,
    el: &Element,
    active_key: Option<&neoflash_core::Keyframe>,
    bitmap_fill: Option<(String, [f64; 6], bool, bool)>,
    resource_filenames: &BTreeMap<String, String>,
    font_family_overrides: &BTreeMap<String, String>,
    shape_catalog: &mut Vec<EncodedShape>,
    text_catalog: &mut Vec<EncodedText>,
    bitmap_catalog: &mut Vec<EncodedBitmap>,
    video_catalog: &mut Vec<EncodedVideo>,
    intern_shape: &FS,
    intern_text: &FT,
    intern_bitmap: &FB,
    intern_video: &FV,
) -> Option<EncodedPayload>
where
    FS: Fn(&mut Vec<EncodedShape>, EncodedShape) -> usize,
    FT: Fn(&mut Vec<EncodedText>, EncodedText) -> usize,
    FB: Fn(&mut Vec<EncodedBitmap>, EncodedBitmap) -> usize,
    FV: Fn(&mut Vec<EncodedVideo>, EncodedVideo) -> usize,
{
    let profile = el.stroke_width_profile();
    match &el.kind {
        ElementKind::Rectangle {
            width,
            height,
            fill,
            stroke,
            stroke_width,
        } => {
            if *width <= 0.0 || *height <= 0.0 {
                return None;
            }
            let commands = rectangle_path_commands(*width, *height, el.rectangle_options());
            let expanded_stroke = if *stroke_width > 0.0 && !profile.is_default() {
                expand_variable_width_stroke(&commands, *stroke_width, &profile)
            } else {
                Vec::new()
            };
            let idx = intern_shape(
                shape_catalog,
                EncodedShape {
                    commands,
                    fill_rule: FillRule::NonZero,
                    fill: *fill,
                    fill_gradient: None,
                    bitmap_fill,
                    stroke: *stroke,
                    stroke_gradient: None,
                    stroke_width: *stroke_width,
                    expanded_stroke,
                },
            );
            Some(EncodedPayload::Shape(idx))
        }
        ElementKind::Ellipse {
            width,
            height,
            fill,
            stroke,
            stroke_width,
        } => {
            if *width <= 0.0 || *height <= 0.0 {
                return None;
            }
            let oval_opts = el.oval_options();
            let commands = oval_path_commands(*width, *height, oval_opts);
            let expanded_stroke = if *stroke_width > 0.0 && !profile.is_default() {
                expand_variable_width_stroke(&commands, *stroke_width, &profile)
            } else {
                Vec::new()
            };
            let idx = intern_shape(
                shape_catalog,
                EncodedShape {
                    commands,
                    fill_rule: FillRule::NonZero,
                    fill: if oval_opts.close_path {
                        *fill
                    } else {
                        [0, 0, 0, 0]
                    },
                    fill_gradient: None,
                    bitmap_fill,
                    stroke: *stroke,
                    stroke_gradient: None,
                    stroke_width: *stroke_width,
                    expanded_stroke,
                },
            );
            Some(EncodedPayload::Shape(idx))
        }
        ElementKind::Path {
            commands,
            fill_rule,
            fill,
            stroke,
            stroke_width,
        } => {
            if commands.is_empty() {
                return None;
            }
            let expanded_stroke = if *stroke_width > 0.0 && !profile.is_default() {
                expand_variable_width_stroke(commands, *stroke_width, &profile)
            } else {
                Vec::new()
            };
            let idx = intern_shape(
                shape_catalog,
                EncodedShape {
                    commands: commands.clone(),
                    fill_rule: *fill_rule,
                    fill: *fill,
                    fill_gradient: None,
                    bitmap_fill,
                    stroke: *stroke,
                    stroke_gradient: None,
                    stroke_width: *stroke_width,
                    expanded_stroke,
                },
            );
            Some(EncodedPayload::Shape(idx))
        }
        ElementKind::PaintedPath {
            commands,
            fill_rule,
            fill,
            stroke,
            fill_gradient,
            stroke_gradient,
            stroke_width,
        } => {
            if commands.is_empty() {
                return None;
            }
            let expanded_stroke = if *stroke_width > 0.0 && !profile.is_default() {
                expand_variable_width_stroke(commands, *stroke_width, &profile)
            } else {
                Vec::new()
            };
            let idx = intern_shape(
                shape_catalog,
                EncodedShape {
                    commands: commands.clone(),
                    fill_rule: *fill_rule,
                    fill: *fill,
                    fill_gradient: fill_gradient.clone(),
                    bitmap_fill,
                    stroke: *stroke,
                    stroke_gradient: stroke_gradient.clone(),
                    stroke_width: *stroke_width,
                    expanded_stroke,
                },
            );
            Some(EncodedPayload::Shape(idx))
        }
        ElementKind::Text {
            text,
            font_family,
            font_size,
            color,
        } => {
            let resolved_font = font_family_overrides
                .get(&font_family.to_ascii_lowercase())
                .cloned()
                .unwrap_or_else(|| font_family.clone());
            let idx = intern_text(
                text_catalog,
                EncodedText {
                    text: text.clone(),
                    font_family: resolved_font,
                    font_size: *font_size,
                    color: *color,
                    bold: false,
                    italic: false,
                    underline: false,
                    align: TextAlign::Left,
                    leading: 0.0,
                    letter_spacing: 0.0,
                    box_size: None,
                    word_wrap: false,
                    multiline: true,
                    border: false,
                    border_color: [0, 0, 0, 255],
                    background: false,
                    background_color: [255, 255, 255, 255],
                },
            );
            Some(EncodedPayload::Text(idx))
        }
        ElementKind::TextBox {
            text,
            width,
            height,
            format,
            word_wrap,
            multiline,
        } => {
            let resolved_font = font_family_overrides
                .get(&format.font.to_ascii_lowercase())
                .cloned()
                .unwrap_or_else(|| format.font.clone());
            let rgb = format.color;
            let color = [(rgb >> 16) as u8, (rgb >> 8) as u8, rgb as u8, 255];
            let field_opts = format.field_options();
            let border = field_opts.as_ref().is_some_and(|o| o.border);
            let background = field_opts.as_ref().is_some_and(|o| o.background);
            let idx = intern_text(
                text_catalog,
                EncodedText {
                    text: text.clone(),
                    font_family: resolved_font,
                    font_size: format.size,
                    color,
                    bold: format.bold,
                    italic: format.italic,
                    underline: format.underline,
                    align: format.align,
                    leading: format.leading,
                    letter_spacing: format.letter_spacing,
                    box_size: Some((*width, *height)),
                    word_wrap: *word_wrap,
                    multiline: *multiline,
                    border,
                    border_color: [0, 0, 0, 255],
                    background,
                    background_color: [255, 255, 255, 255],
                },
            );
            Some(EncodedPayload::Text(idx))
        }
        ElementKind::Bitmap {
            resource_id,
            width,
            height,
            smoothing,
        } => {
            let res_name = resource_filenames
                .get(resource_id)
                .cloned()
                .unwrap_or_default();
            let idx = intern_bitmap(
                bitmap_catalog,
                EncodedBitmap {
                    resource_name: res_name,
                    width: f64::from(*width),
                    height: f64::from(*height),
                    smoothing: *smoothing,
                },
            );
            Some(EncodedPayload::Bitmap(idx))
        }
        ElementKind::Video { width, height } => {
            let source = active_key
                .and_then(|k| k.video.as_ref())
                .and_then(|span| {
                    if let Some(mapped) = resource_filenames.get(&span.resource) {
                        return Some(mapped.clone());
                    }
                    resolve_video_source(project, span).map(|s| s.url_or_path)
                })
                .unwrap_or_default();
            let idx = intern_video(
                video_catalog,
                EncodedVideo {
                    source,
                    width: *width,
                    height: *height,
                },
            );
            Some(EncodedPayload::Video(idx))
        }
        ElementKind::Instance {
            symbol_id,
            playback,
        } => {
            let child_sym = project.symbol(symbol_id)?;
            let eff_kind = el.effective_symbol_kind_for(child_sym);
            let p_start = placement_start(layer, frame, &el.id);
            Some(EncodedPayload::Instance {
                symbol_id: symbol_id.clone(),
                symbol_kind: eff_kind,
                playback: *playback,
                placement_start_frame: p_start,
                synced_to_parent: synced_layer,
            })
        }
    }
}

fn collect_named_instance_bindings(
    layers: &[EncodedLayer],
    class_name_by_symbol_id: &BTreeMap<String, String>,
    properties_swift: &str,
) -> Vec<NamedInstanceBinding> {
    let reserved: BTreeSet<&str> = BTreeSet::from([
        "name",
        "parent",
        "mask",
        "x",
        "y",
        "scaleX",
        "scaleY",
        "rotation",
        "skew",
        "alpha",
        "visible",
        "width",
        "height",
        "_x",
        "_y",
        "_xscale",
        "_yscale",
        "_rotation",
        "_alpha",
        "_visible",
        "_width",
        "_height",
        "isScriptControlled",
        "colorTransform",
        "blendMode",
        "filters",
        "stage",
        "root",
        "children",
        "graphics",
        "buttonMode",
        "mouseEnabled",
        "mouseChildren",
        "dynamicProps",
        "numChildren",
        "currentFrame",
        "totalFrames",
        "isPlaying",
        "symbolKind",
        "graphicPlayback",
        "frameLabels",
        "scenes",
        "stageMetadata",
        "host",
        "timelineSpec",
        "currentLabel",
        "enabled",
        "buttonState",
        "self",
        "super",
    ]);

    let mut by_raw_name: BTreeMap<String, (String, String)> = BTreeMap::new();
    for layer in layers {
        if layer.is_mask {
            continue;
        }
        for span in &layer.spans {
            for placement in &span.placements {
                let raw = placement.name.trim();
                if raw.is_empty() {
                    continue;
                }
                let (ty, init_expr) = match &placement.payload {
                    EncodedPayload::Shape(_) => (
                        "NFShape".to_owned(),
                        format!("NFShape(name: {})", swift_str(raw)),
                    ),
                    EncodedPayload::Text(_) => (
                        "NFTextField".to_owned(),
                        format!("NFTextField(name: {})", swift_str(raw)),
                    ),
                    EncodedPayload::Bitmap(_) => (
                        "NFBitmap".to_owned(),
                        format!(
                            "NFBitmap(name: {}, spec: NFBitmapSpec(resourceName: \"\", width: 0, height: 0))",
                            swift_str(raw)
                        ),
                    ),
                    EncodedPayload::Video(_) => (
                        "NFVideo".to_owned(),
                        format!(
                            "NFVideo(name: {}, spec: NFVideoSpec(source: \"\", width: 0, height: 0))",
                            swift_str(raw)
                        ),
                    ),
                    EncodedPayload::Instance { symbol_id, .. } => {
                        if let Some(cls) = class_name_by_symbol_id.get(symbol_id) {
                            (cls.clone(), format!("{cls}(name: {})", swift_str(raw)))
                        } else {
                            (
                                "NFMovieClip".to_owned(),
                                format!("NFMovieClip(name: {})", swift_str(raw)),
                            )
                        }
                    }
                };

                by_raw_name
                    .entry(raw.to_owned())
                    .and_modify(|existing| {
                        if existing.0 != ty {
                            existing.0 = "NFDisplayObject".to_owned();
                            existing.1 = format!("NFDisplayObject(name: {})", swift_str(raw));
                        }
                    })
                    .or_insert((ty, init_expr));
            }
        }
    }

    let mut used_props: BTreeSet<String> = reserved.iter().map(|s| (*s).to_owned()).collect();
    let mut result = Vec::new();
    for (raw_name, (swift_type, init_expr)) in by_raw_name {
        let prop_name = sanitize_swift_identifier(&raw_name, "instance");
        if used_props.contains(&prop_name) {
            continue;
        }
        // Skip if already explicitly declared in properties_swift
        if properties_swift.contains(&format!("var {prop_name}:"))
            || properties_swift.contains(&format!("let {prop_name}:"))
            || properties_swift.contains(&format!("var {prop_name} ="))
        {
            continue;
        }
        used_props.insert(prop_name.clone());
        result.push(NamedInstanceBinding {
            raw_name,
            swift_prop_name: prop_name,
            swift_type,
            init_expr,
        });
    }
    result
}

#[allow(clippy::too_many_arguments)]
fn emit_timeline_spec_constant(
    out: &mut String,
    total_frames: u32,
    timeline: &Timeline,
    scene_ranges: &[SceneRange],
    sounds_by_frame: &BTreeMap<u32, Vec<&FrameSound>>,
    resource_filenames: &BTreeMap<String, String>,
    shape_catalog: &[EncodedShape],
    text_catalog: &[EncodedText],
    bitmap_catalog: &[EncodedBitmap],
    video_catalog: &[EncodedVideo],
    encoded_layers: &[EncodedLayer],
) {
    let _ = writeln!(
        out,
        "    private static let _nfTimelineSpec = NFTimelineSpec("
    );
    let _ = writeln!(out, "        totalFrames: {total_frames},");

    // Shapes
    if shape_catalog.is_empty() {
        let _ = writeln!(out, "        shapes: [],");
    } else {
        let _ = writeln!(out, "        shapes: [");
        for shape in shape_catalog {
            emit_vector_shape_literal(out, shape);
        }
        let _ = writeln!(out, "        ],");
    }

    // Texts
    if text_catalog.is_empty() {
        let _ = writeln!(out, "        texts: [],");
    } else {
        let _ = writeln!(out, "        texts: [");
        for txt in text_catalog {
            emit_text_spec_literal(out, txt);
        }
        let _ = writeln!(out, "        ],");
    }

    // Bitmaps
    if bitmap_catalog.is_empty() {
        let _ = writeln!(out, "        bitmaps: [],");
    } else {
        let _ = writeln!(out, "        bitmaps: [");
        for bmp in bitmap_catalog {
            let _ = writeln!(
                out,
                "            NFBitmapSpec(resourceName: {}, width: {}, height: {}, smoothing: {}),",
                swift_str(&bmp.resource_name),
                fmt_f64(bmp.width),
                fmt_f64(bmp.height),
                bmp.smoothing
            );
        }
        let _ = writeln!(out, "        ],");
    }

    // Videos
    if video_catalog.is_empty() {
        let _ = writeln!(out, "        videos: [],");
    } else {
        let _ = writeln!(out, "        videos: [");
        for vid in video_catalog {
            let _ = writeln!(
                out,
                "            NFVideoSpec(source: {}, width: {}, height: {}),",
                swift_str(&vid.source),
                fmt_f64(vid.width),
                fmt_f64(vid.height)
            );
        }
        let _ = writeln!(out, "        ],");
    }

    // Navigable frame labels (1-based frame index)
    let labels = timeline.navigable_labels();
    if labels.is_empty() {
        let _ = writeln!(out, "        labels: [:],");
    } else {
        let mut unique_labels: BTreeMap<&str, u32> = BTreeMap::new();
        for (lbl, frame0) in labels {
            unique_labels.entry(lbl).or_insert(frame0 + 1);
        }
        let entries: Vec<String> = unique_labels
            .into_iter()
            .map(|(k, v)| format!("{}: {v}", swift_str(k)))
            .collect();
        let _ = writeln!(out, "        labels: [{}],", entries.join(", "));
    }

    // Scene ranges
    if scene_ranges.is_empty() {
        let _ = writeln!(out, "        scenes: [],");
    } else {
        let _ = writeln!(out, "        scenes: [");
        for sr in scene_ranges {
            let _ = writeln!(
                out,
                "            NFSceneRange(name: {}, startFrame: {}, frameCount: {}),",
                swift_str(&sr.name),
                sr.start,
                sr.frames
            );
        }
        let _ = writeln!(out, "        ],");
    }

    // Frame sounds
    if sounds_by_frame.is_empty() {
        let _ = writeln!(out, "        soundsByFrame: [:],");
    } else {
        let _ = writeln!(out, "        soundsByFrame: [");
        for (&frame0, snds) in sounds_by_frame {
            let mut cmd_literals = Vec::new();
            for snd in snds {
                let res_file = resource_filenames
                    .get(&snd.resource)
                    .cloned()
                    .unwrap_or_else(|| snd.resource.clone());
                let sync_lit = match snd.sync {
                    SoundSync::Event => ".event",
                    SoundSync::Start => ".start",
                    SoundSync::Stop => ".stop",
                    SoundSync::Stream => ".stream",
                };
                let (gain_l, gain_r) = snd.gains_at(0.0);
                let vol = ((gain_l + gain_r) * 0.5).clamp(0.0, 1.0);
                let pan = (gain_r - gain_l).clamp(-1.0, 1.0);
                let in_pt = snd.in_point.map_or_else(|| "nil".to_owned(), fmt_f64);
                let out_pt = snd.out_point.map_or_else(|| "nil".to_owned(), fmt_f64);
                cmd_literals.push(format!(
                    "NFSoundCommand(resourceName: {}, sync: {sync_lit}, loops: {}, loopForever: {}, inPoint: {in_pt}, outPoint: {out_pt}, volume: {}, pan: {})",
                    swift_str(&res_file),
                    snd.loops.max(1),
                    snd.loop_forever,
                    fmt_f64(vol),
                    fmt_f64(pan)
                ));
            }
            let _ = writeln!(out, "            {frame0}: [{}],", cmd_literals.join(", "));
        }
        let _ = writeln!(out, "        ],");
    }

    // Layers
    if encoded_layers.is_empty() {
        let _ = writeln!(out, "        layers: []");
    } else {
        let _ = writeln!(out, "        layers: [");
        for layer in encoded_layers {
            let masked_lit = layer
                .masked_by_layer_index
                .map_or_else(|| "nil".to_owned(), |i| i.to_string());
            let _ = writeln!(
                out,
                "            NFLayerSpec(layerIndex: {}, name: {}, isMask: {}, maskedByLayerIndex: {masked_lit}, blendMode: {}, spans: [",
                layer.layer_index,
                swift_str(&layer.name),
                layer.is_mask,
                swift_blend_mode(layer.blend_mode)
            );
            for span in &layer.spans {
                let _ = writeln!(
                    out,
                    "                NFFrameSpan(startFrame: {}, endFrame: {}, placements: [",
                    span.start_frame, span.end_frame
                );
                for p in &span.placements {
                    emit_placement_literal(out, p);
                }
                let _ = writeln!(out, "                ]),");
            }
            let _ = writeln!(out, "            ]),");
        }
        let _ = writeln!(out, "        ]");
    }
    let _ = writeln!(out, "    )");
    let _ = writeln!(out);
}

fn emit_vector_shape_literal(out: &mut String, shape: &EncodedShape) {
    let cmds = format_path_commands(&shape.commands);
    let fill_rule = match shape.fill_rule {
        FillRule::NonZero => ".nonZero",
        FillRule::EvenOdd => ".evenOdd",
    };
    let fill_grad = shape
        .fill_gradient
        .as_ref()
        .map_or_else(|| "nil".to_owned(), format_gradient_paint);
    let bmp_fill = shape.bitmap_fill.as_ref().map_or_else(
        || "nil".to_owned(),
        |(res, m, repeat, smooth)| {
            format!(
                "NFBitmapFillPaint(resourceName: {}, matrix: {}, repeatPattern: {repeat}, smoothing: {smooth})",
                swift_str(res),
                format_matrix(*m)
            )
        },
    );
    let stroke_grad = shape
        .stroke_gradient
        .as_ref()
        .map_or_else(|| "nil".to_owned(), format_gradient_paint);
    let expanded = if shape.expanded_stroke.is_empty() {
        "[]".to_owned()
    } else {
        format_path_commands(&shape.expanded_stroke)
    };
    let _ = writeln!(
        out,
        "            NFVectorShape(commands: {cmds}, fillRule: {fill_rule}, fillColor: {}, fillGradient: {fill_grad}, bitmapFill: {bmp_fill}, strokeColor: {}, strokeGradient: {stroke_grad}, strokeWidth: {}, expandedStrokeCommands: {expanded}),",
        format_color(shape.fill),
        format_color(shape.stroke),
        fmt_f64(shape.stroke_width)
    );
}

fn emit_text_spec_literal(out: &mut String, txt: &EncodedText) {
    let align_lit = match txt.align {
        TextAlign::Left => ".left",
        TextAlign::Center => ".center",
        TextAlign::Right => ".right",
    };
    let (bw, bh) = match txt.box_size {
        Some((w, h)) => (fmt_f64(w), fmt_f64(h)),
        None => ("nil".to_owned(), "nil".to_owned()),
    };
    let _ = writeln!(
        out,
        "            NFTextSpec(text: {}, fontFamily: {}, fontSize: {}, color: {}, bold: {}, italic: {}, underline: {}, align: {align_lit}, leading: {}, letterSpacing: {}, boxWidth: {bw}, boxHeight: {bh}, wordWrap: {}, multiline: {}, border: {}, borderColor: {}, background: {}, backgroundColor: {}),",
        swift_str(&txt.text),
        swift_str(&txt.font_family),
        fmt_f64(txt.font_size),
        format_color(txt.color),
        txt.bold,
        txt.italic,
        txt.underline,
        fmt_f64(txt.leading),
        fmt_f64(txt.letter_spacing),
        txt.word_wrap,
        txt.multiline,
        txt.border,
        format_color(txt.border_color),
        txt.background,
        format_color(txt.background_color)
    );
}

fn emit_placement_literal(out: &mut String, p: &EncodedPlacement) {
    let payload_lit = match &p.payload {
        EncodedPayload::Shape(i) => format!(".shape({i})"),
        EncodedPayload::Text(i) => format!(".text({i})"),
        EncodedPayload::Bitmap(i) => format!(".bitmap({i})"),
        EncodedPayload::Video(i) => format!(".video({i})"),
        EncodedPayload::Instance {
            symbol_id,
            symbol_kind,
            playback,
            placement_start_frame,
            synced_to_parent,
        } => {
            let kind_lit = match symbol_kind {
                SymbolKind::MovieClip => ".movieClip",
                SymbolKind::Graphic => ".graphic",
                SymbolKind::Button => ".button",
            };
            let pb_lit = match playback {
                InstancePlayback::Independent => ".independent".to_owned(),
                InstancePlayback::Loop => ".loop(startFrame: 0)".to_owned(),
                InstancePlayback::LoopFrom(s) => format!(".loop(startFrame: {s})"),
                InstancePlayback::PlayOnce => ".playOnce(startFrame: 0)".to_owned(),
                InstancePlayback::PlayOnceFrom(s) => format!(".playOnce(startFrame: {s})"),
                InstancePlayback::SingleFrame(f) => format!(".singleFrame(frame: {f})"),
            };
            format!(
                ".instance(NFInstanceSpec(symbolId: {}, symbolKind: {kind_lit}, playback: {pb_lit}, placementStartFrame: {placement_start_frame}, syncedToParent: {synced_to_parent}))",
                swift_str(symbol_id)
            )
        }
    };

    let ct_lit = if p.color_transform.is_identity() {
        ".identity".to_owned()
    } else {
        let m = p.color_transform.multipliers;
        let o = p.color_transform.offsets;
        format!(
            "NFColorTransform(redMultiplier: {}, greenMultiplier: {}, blueMultiplier: {}, alphaMultiplier: {}, redOffset: {}, greenOffset: {}, blueOffset: {}, alphaOffset: {})",
            fmt_f64(m[0]),
            fmt_f64(m[1]),
            fmt_f64(m[2]),
            fmt_f64(m[3]),
            fmt_f64(o[0]),
            fmt_f64(o[1]),
            fmt_f64(o[2]),
            fmt_f64(o[3])
        )
    };

    let filters_lit = format_filters(&p.filters);
    let _ = writeln!(
        out,
        "                    NFPlacementSpec(elementId: {}, name: {}, x: {}, y: {}, scaleX: {}, scaleY: {}, rotation: {}, skew: {}, matrix: {}, alpha: {}, colorTransform: {ct_lit}, visible: {}, blendMode: {}, filters: {filters_lit}, payload: {payload_lit}),",
        swift_str(&p.element_id),
        swift_str(&p.name),
        fmt_f64(p.x),
        fmt_f64(p.y),
        fmt_f64(p.scale_x),
        fmt_f64(p.scale_y),
        fmt_f64(p.rotation),
        fmt_f64(p.skew),
        format_matrix(p.matrix),
        fmt_f64(p.alpha),
        p.visible,
        swift_blend_mode(p.blend_mode)
    );
}

fn emit_symbol_script_methods(out: &mut String, bundle: &XcodeSymbolScriptBundle) {
    if !bundle.helper_methods_swift.trim().is_empty() {
        let _ = writeln!(out);
        for line in bundle.helper_methods_swift.lines() {
            let _ = writeln!(out, "    {line}");
        }
    }

    if !bundle.frame_methods_swift.is_empty() {
        let mut frame_dispatch: Vec<(u32, String)> = Vec::new();
        for (&frame0, code) in &bundle.frame_methods_swift {
            if code.trim().is_empty() {
                continue;
            }
            let _ = writeln!(out);
            if let Some(declared_fn) = extract_declared_func_name(code) {
                for line in code.lines() {
                    let _ = writeln!(out, "    {line}");
                }
                frame_dispatch.push((frame0, declared_fn));
            } else {
                let fn_name = format!("_nfFrameScript_{frame0}");
                let _ = writeln!(out, "    private func {fn_name}() {{");
                for line in code.lines() {
                    let _ = writeln!(out, "        {line}");
                }
                let _ = writeln!(out, "    }}");
                frame_dispatch.push((frame0, fn_name));
            }
        }

        if !frame_dispatch.is_empty() {
            let _ = writeln!(out);
            let _ = writeln!(
                out,
                "    public override func runFrameScript(frameIndex: Int) {{"
            );
            let _ = writeln!(out, "        switch frameIndex {{");
            for (f0, fn_name) in frame_dispatch {
                let _ = writeln!(out, "        case {f0}: self.{fn_name}()");
            }
            let _ = writeln!(out, "        default: break");
            let _ = writeln!(out, "        }}");
            let _ = writeln!(out, "    }}");
        }
    }

    if !bundle.instance_handlers_swift.is_empty() {
        let mut handler_entries: Vec<(String, ObjectEvent, String)> = Vec::new();
        for (idx, (target_key, event, code)) in bundle.instance_handlers_swift.iter().enumerate() {
            if code.trim().is_empty() {
                continue;
            }
            let _ = writeln!(out);
            let fn_name = if let Some(declared) = extract_declared_func_name(code) {
                for line in code.lines() {
                    let _ = writeln!(out, "    {line}");
                }
                declared
            } else {
                let gen_name = format!("_nfInstanceHandler_{idx}");
                let _ = writeln!(out, "    private func {gen_name}() {{");
                for line in code.lines() {
                    let _ = writeln!(out, "        {line}");
                }
                let _ = writeln!(out, "    }}");
                gen_name
            };
            handler_entries.push((target_key.clone(), *event, fn_name));
        }

        if !handler_entries.is_empty() {
            let _ = writeln!(out);
            let _ = writeln!(
                out,
                "    public override func attachInstanceHandlers(elementId: String, name: String, target: NFDisplayObject) {{"
            );
            for (target_key, event, fn_name) in handler_entries {
                let key_lit = swift_str(&target_key);
                let arr_prop = match event {
                    ObjectEvent::Load => "loadCallbacks",
                    ObjectEvent::Click => "clickCallbacks",
                    ObjectEvent::EnterFrame => "enterFrameCallbacks",
                };
                let _ = writeln!(
                    out,
                    "        if elementId == {key_lit} || name == {key_lit} {{"
                );
                let _ = writeln!(
                    out,
                    "            target.{arr_prop}.append({{ [weak self] in self?.{fn_name}() }})"
                );
                let _ = writeln!(out, "        }}");
            }
            let _ = writeln!(out, "    }}");
        }
    }
}

fn extract_declared_func_name(code: &str) -> Option<String> {
    let trimmed = code.trim_start();
    let trimmed = trimmed
        .strip_prefix("@MainActor")
        .map(str::trim_start)
        .unwrap_or(trimmed);
    let rest = trimmed
        .strip_prefix("private func ")
        .or_else(|| trimmed.strip_prefix("public func "))
        .or_else(|| trimmed.strip_prefix("internal func "))
        .or_else(|| trimmed.strip_prefix("func "))?;
    let name: String = rest
        .chars()
        .take_while(|c| c.is_ascii_alphanumeric() || *c == '_')
        .collect();
    let after = rest[name.len()..].trim_start();
    if !name.is_empty() && after.starts_with("()") {
        Some(name)
    } else {
        None
    }
}

fn format_path_commands(commands: &[PathCommand]) -> String {
    let parts: Vec<String> = commands
        .iter()
        .map(|cmd| match *cmd {
            PathCommand::MoveTo { x, y } => format!(".moveTo({}, {})", fmt_f64(x), fmt_f64(y)),
            PathCommand::LineTo { x, y } => format!(".lineTo({}, {})", fmt_f64(x), fmt_f64(y)),
            PathCommand::QuadraticTo { cx, cy, x, y } => format!(
                ".quadTo({}, {}, {}, {})",
                fmt_f64(cx),
                fmt_f64(cy),
                fmt_f64(x),
                fmt_f64(y)
            ),
            PathCommand::CubicTo {
                cx1,
                cy1,
                cx2,
                cy2,
                x,
                y,
            } => format!(
                ".cubicTo({}, {}, {}, {}, {}, {})",
                fmt_f64(cx1),
                fmt_f64(cy1),
                fmt_f64(cx2),
                fmt_f64(cy2),
                fmt_f64(x),
                fmt_f64(y)
            ),
            PathCommand::Close => ".close".to_owned(),
        })
        .collect();
    format!("[{}]", parts.join(", "))
}

fn format_gradient_paint(paint: &GradientPaint) -> String {
    let kind = match paint.kind {
        GradientKind::Linear => ".linear",
        GradientKind::Radial => ".radial",
    };
    let spread = match paint.spread {
        GradientSpread::Extend => ".extend",
        GradientSpread::Reflect => ".reflect",
        GradientSpread::Repeat => ".repeatSpread",
    };
    let stops: Vec<String> = paint
        .stops
        .iter()
        .map(|s| {
            format!(
                "NFGradientStop(ratio: {}, color: {})",
                s.ratio,
                format_color(s.color)
            )
        })
        .collect();
    format!(
        "NFGradientPaint(kind: {kind}, matrix: {}, stops: [{}], focalPointRatio: {}, spread: {spread}, linearRGB: {})",
        format_matrix(paint.matrix),
        stops.join(", "),
        fmt_f64(paint.focal_point_ratio),
        paint.linear_rgb
    )
}

fn format_filters(filters: &[FilterSpec]) -> String {
    let mut items = Vec::new();
    for f in filters {
        if !f.is_enabled() || f.as_displacement().is_some() || f.as_shader().is_some() {
            continue;
        }
        match f {
            FilterSpec::DropShadow {
                distance,
                angle,
                color,
                alpha,
                blur_x,
                blur_y,
                ..
            } => {
                let c = rgb_alpha_to_color(*color, *alpha);
                items.push(format!(
                    ".dropShadow(distance: {}, angleDegrees: {}, color: {}, blurX: {}, blurY: {})",
                    fmt_f64(*distance),
                    fmt_f64(*angle),
                    format_color(c),
                    fmt_f64(*blur_x),
                    fmt_f64(*blur_y)
                ));
            }
            FilterSpec::Glow {
                color,
                alpha,
                blur_x,
                blur_y,
                ..
            } => {
                let c = rgb_alpha_to_color(*color, *alpha);
                items.push(format!(
                    ".glow(color: {}, blurX: {}, blurY: {})",
                    format_color(c),
                    fmt_f64(*blur_x),
                    fmt_f64(*blur_y)
                ));
            }
            FilterSpec::Blur { blur_x, blur_y, .. } => {
                items.push(format!(
                    ".blur(blurX: {}, blurY: {})",
                    fmt_f64(*blur_x),
                    fmt_f64(*blur_y)
                ));
            }
            _ => {}
        }
    }
    if items.is_empty() {
        "[]".to_owned()
    } else {
        format!("[{}]", items.join(", "))
    }
}

fn rgb_alpha_to_color(rgb: u32, alpha: f64) -> Color {
    [
        ((rgb >> 16) & 0xff) as u8,
        ((rgb >> 8) & 0xff) as u8,
        (rgb & 0xff) as u8,
        (alpha.clamp(0.0, 1.0) * 255.0).round() as u8,
    ]
}

fn format_color(c: Color) -> String {
    if c == [0, 0, 0, 0] {
        ".clear".to_owned()
    } else {
        format!(
            "NFColor(r: {}, g: {}, b: {}, a: {})",
            c[0], c[1], c[2], c[3]
        )
    }
}

fn format_matrix(m: [f64; 6]) -> String {
    if (m[0] - 1.0).abs() < 1e-9
        && m[1].abs() < 1e-9
        && m[2].abs() < 1e-9
        && (m[3] - 1.0).abs() < 1e-9
        && m[4].abs() < 1e-9
        && m[5].abs() < 1e-9
    {
        ".identity".to_owned()
    } else {
        format!(
            "NFAffineMatrix(a: {}, b: {}, c: {}, d: {}, tx: {}, ty: {})",
            fmt_f64(m[0]),
            fmt_f64(m[1]),
            fmt_f64(m[2]),
            fmt_f64(m[3]),
            fmt_f64(m[4]),
            fmt_f64(m[5])
        )
    }
}

fn swift_blend_mode(mode: BlendMode) -> &'static str {
    match mode {
        BlendMode::Normal => ".normal",
        BlendMode::Layer => ".layer",
        BlendMode::Multiply => ".multiply",
        BlendMode::Screen => ".screen",
        BlendMode::Lighten => ".lighten",
        BlendMode::Darken => ".darken",
        BlendMode::Difference => ".difference",
        BlendMode::Add => ".add",
        BlendMode::Subtract => ".subtract",
        BlendMode::Invert => ".invert",
        BlendMode::Alpha => ".alpha",
        BlendMode::Erase => ".erase",
        BlendMode::Overlay => ".overlay",
        BlendMode::Hardlight => ".hardlight",
    }
}

fn fmt_f64(v: f64) -> String {
    if !v.is_finite() {
        return "0.0".to_owned();
    }
    let rounded = (v * 1_000_000.0).round() / 1_000_000.0;
    let clean = if rounded == -0.0 { 0.0 } else { rounded };
    let mut s = format!("{clean}");
    if !s.contains('.') && !s.contains('e') && !s.contains('E') {
        s.push_str(".0");
    }
    s
}

fn swift_str(s: &str) -> String {
    let mut out = String::with_capacity(s.len() + 2);
    out.push('"');
    for ch in s.chars() {
        match ch {
            '\\' => out.push_str("\\\\"),
            '"' => out.push_str("\\\""),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            c if c.is_control() => {
                let _ = write!(out, "\\u{{{:x}}}", c as u32);
            }
            other => out.push(other),
        }
    }
    out.push('"');
    out
}
